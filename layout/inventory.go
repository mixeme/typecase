package layout

// InventoryEntry is how one mockup .m-* class is accounted for.
// Exactly one of Selector, NotAWidget, Deferred is set.
type InventoryEntry struct {
	Selector   string // Typecase selector when this class maps to a widget
	NotAWidget string // reason this is page/desktop chrome, not a Typecase widget
	Deferred   string // reason and plan step when transfer is later or out of scope
}

func mapped(sel string) InventoryEntry { return InventoryEntry{Selector: sel} }
func notAWidget(reason string) InventoryEntry {
	return InventoryEntry{NotAWidget: reason}
}
func deferred(reason string) InventoryEntry { return InventoryEntry{Deferred: reason} }

